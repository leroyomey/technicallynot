// Writes one conversation file; `age` minutes old. → its id.
function conv(dir, lines, age = 0, id = uuid()) {
  const f = path.join(dir, id + '.jsonl');
  fs.writeFileSync(f, lines.join('\n') + '\n');
  const t = new Date(Date.now() - age * 60000);
  fs.utimesSync(f, t, t);
  return id;
}

// Every read of a file is counted: the largest part asked for, and whether a whole file was ever
// read.
const reads = [],
  whole = [],
  realOpen = fs.promises.open,
  realReadFile = fs.promises.readFile,
  realReadFileSync = fs.readFileSync;
fs.promises.open = async (file, ...rest) => {
  const fh = await realOpen.call(fs.promises, file, ...rest),
    read = fh.read.bind(fh);
  fh.read = (buf, off, len, pos) => {
    reads.push({ file: String(file), len, pos });
    return read(buf, off, len, pos);
  };
  return fh;
};
fs.promises.readFile = (file, ...rest) => {
  if (/\.jsonl$/.test(String(file))) whole.push(String(file));
  return realReadFile.call(fs.promises, file, ...rest);
};

